#!/usr/bin/env node
/**
 * cf-monitor CLI generates main paths relative to repo root, but wrangler
 * resolves paths relative to `.cf-monitor/wrangler.jsonc`. Fix before deploy.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";

const path = ".cf-monitor/wrangler.jsonc";
if (!existsSync(path)) {
  console.error("Missing .cf-monitor/wrangler.jsonc — run: npx cf-monitor init");
  process.exit(1);
}

const raw = readFileSync(path, "utf8");
const stripped = raw.replace(/^\s*\/\/.*$/gm, "");
const cfg = JSON.parse(stripped);
const desired = "../node_modules/@littlebearapps/cf-monitor/worker/index.ts";
if (cfg.main !== desired) {
  cfg.main = desired;
  writeFileSync(
    path,
    `// Auto-generated by cf-monitor CLI — edit cf-monitor.yaml instead\n${JSON.stringify(cfg, null, 2)}\n`,
  );
  console.log(`Fixed main → ${desired}`);
} else {
  console.log("main path OK");
}
