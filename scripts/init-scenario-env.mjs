#!/usr/bin/env node
/**
 * Copy scenario env examples and generate per-peer HMAC secrets locally.
 *
 *   node scripts/init-scenario-env.mjs
 *   node scripts/init-scenario-env.mjs --scenario smart-site
 *
 * Never overwrites an existing env / peers.env / peers.secrets.env.
 * Secrets stay gitignored. They are not written into sibling product repos.
 */
import { randomBytes } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { scenariosRoot } from "./lib/scenario-pack.mjs";
import { metaRoot } from "./lib/workspace.mjs";

const thisFile = fileURLToPath(import.meta.url);

export const SCENARIO_ENV_BASENAMES = ["env", "peers.env", "peers.secrets.env"];

export function parseDotEnv(text) {
  const out = {};
  for (const rawLine of String(text).split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line || line.startsWith("#")) continue;
    const idx = line.indexOf("=");
    if (idx < 1) continue;
    const key = line.slice(0, idx).trim();
    let value = line.slice(idx + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    out[key] = value;
  }
  return out;
}

export function listScenarioEnvFiles(scenarioDir, exists = existsSync) {
  return SCENARIO_ENV_BASENAMES.map((name) => join(scenarioDir, name)).filter((path) =>
    exists(path),
  );
}

function hexSecret() {
  return randomBytes(32).toString("hex");
}

function copyIfMissing(from, to) {
  if (existsSync(to)) return { path: to, action: "kept" };
  if (!existsSync(from)) return { path: to, action: "skipped", reason: `missing ${from}` };
  writeFileSync(to, readFileSync(from));
  return { path: to, action: "copied" };
}

function fillSecrets(examplePath, destPath) {
  if (existsSync(destPath)) return { path: destPath, action: "kept" };
  if (!existsSync(examplePath)) {
    return { path: destPath, action: "skipped", reason: `missing ${examplePath}` };
  }
  const parsed = parseDotEnv(readFileSync(examplePath, "utf8"));
  const hmacKeys = [
    "SYNCROBRAIN_WEBHOOK_SECRET",
    "DOERFLOW_HMAC_SECRET",
    "DOERFLOW_INVOKE_HMAC_SECRET",
    "DOERFLOW_CALLBACK_HMAC_SECRET",
    "TRADING_WEBHOOK_SECRET",
  ];
  const lines = [
    "# Generated by scripts/init-scenario-env.mjs. Gitignored. Copy values into each product env.",
    "# Do not commit. Do not share one file across six products at runtime — copy per product.",
    "",
  ];
  for (const [key, value] of Object.entries(parsed)) {
    if (hmacKeys.includes(key) && !value) {
      lines.push(`${key}=${hexSecret()}`);
    } else {
      lines.push(`${key}=${value}`);
    }
  }
  lines.push("");
  mkdirSync(dirname(destPath), { recursive: true });
  writeFileSync(destPath, lines.join("\n"), { encoding: "utf8" });
  return { path: destPath, action: "generated" };
}

export function initScenarioEnv(options = {}) {
  const scenario = options.scenario ?? "agent-commerce";
  const root = options.scenariosRoot ?? scenariosRoot;
  const dir = join(root, scenario);
  if (!existsSync(dir)) {
    return { ok: false, scenario, dir, results: [], error: `unknown scenario directory: ${dir}` };
  }

  const results = [
    copyIfMissing(join(dir, "env.example"), join(dir, "env")),
    copyIfMissing(join(dir, "peers.env.example"), join(dir, "peers.env")),
    fillSecrets(join(dir, "peers.secrets.env.example"), join(dir, "peers.secrets.env")),
  ];

  if (scenario === "smart-site") {
    const base = join(root, "agent-commerce");
    results.push(
      copyIfMissing(join(base, "env.example"), join(base, "env")),
      copyIfMissing(join(base, "peers.env.example"), join(base, "peers.env")),
      fillSecrets(join(base, "peers.secrets.env.example"), join(base, "peers.secrets.env")),
    );
  }

  const ingressDir = join(root, "ingress");
  if (existsSync(join(ingressDir, "env.example"))) {
    results.push(copyIfMissing(join(ingressDir, "env.example"), join(ingressDir, "env")));
  }

  return { ok: true, scenario, dir, results };
}

function printHelp() {
  console.log(`Usage: node scripts/init-scenario-env.mjs [--scenario agent-commerce|smart-site]

Copies *.example → gitignored env files and generates HMAC secrets once.
Does not overwrite existing files. Does not write into sibling product repos.

Next: copy peers.secrets.env values into each product's own gitignored env
(VistaCast deploy/.env, SyncroBrain deploy/.env.prod, DoerFlow deploy/env/api.env).
`);
}

function main(argv = process.argv.slice(2)) {
  let scenario = "agent-commerce";
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === "--help" || argv[i] === "-h") {
      printHelp();
      return 0;
    }
    if (argv[i] === "--scenario") scenario = argv[++i];
    else if (!argv[i].startsWith("-")) scenario = argv[i];
  }
  const result = initScenarioEnv({ scenario, scenariosRoot });
  if (!result.ok) {
    console.error(`[peers] ${result.error}`);
    return 78;
  }
  for (const item of result.results) {
    const rel = item.path.startsWith(metaRoot) ? item.path.slice(metaRoot.length + 1) : item.path;
    console.log(`[peers] ${item.action.padEnd(9)} ${rel}${item.reason ? ` (${item.reason})` : ""}`);
  }
  console.log(
    "[peers] copy HMAC values into each product env; combination DNS is in peers.env (luminary-control-edge).",
  );
  return 0;
}

if (process.argv[1] === thisFile || process.argv[1]?.endsWith("init-scenario-env.mjs")) {
  process.exit(main());
}
